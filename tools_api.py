"""HW7 §5 protocols. Person 1 owns production Tools; Person 2 owns World."""
from __future__ import annotations
from random import Random
from typing import Any, Protocol, runtime_checkable
from schemas import Bid, Inspection, Order, Reservation, RFQ, StatusUpdate, SupplierProfile

MAX_TOOL_CALLS = 60

class ToolError(RuntimeError): pass
class ToolNotAllowed(ToolError): pass
class ToolBudgetExceeded(ToolError): pass

@runtime_checkable
class Tools(Protocol):
    def today(self) -> int: ...
    def list_suppliers(self, kind: str | None = None) -> list[SupplierProfile]: ...
    def post_rfq(self, rfq: RFQ) -> list[Bid]: ...
    def request_quote(self, supplier_id: str, rfq: RFQ) -> Bid | None: ...
    def award(self, bid_id: str) -> Reservation: ...
    def cancel(self, reservation_id: str) -> dict[str, Any]: ...
    def get_inspection(self, reservation_id: str) -> Inspection | None: ...
    def log(self, msg: str) -> None: ...
    def usage(self) -> dict[str, Any]: ...
    def trace(self) -> list[dict[str, Any]]: ...

@runtime_checkable
class Supplier(Protocol):
    profile: SupplierProfile
    def quote(self, rfq: RFQ, day: int, rng: Random) -> Bid | None: ...
    def accept(self, bid: Bid, day: int) -> Reservation: ...
    def cancel(self, reservation_id: str, day: int) -> float: ...

@runtime_checkable
class Agent(Protocol):
    name: str
    def start(self, order: Order, tools: Tools) -> None: ...
    def on_events(self, day: int, updates: list[StatusUpdate],
                  inspections: list[Inspection], tools: Tools) -> None: ...

@runtime_checkable
class World(Protocol):
    suppliers: dict[str, Supplier]
    day: int
    def __init__(self, order: Order, catalog_path: str, seed: int, unreliability: float): ...
    def advance_day(self) -> tuple[list[StatusUpdate], list[Inspection]]: ...
    def ground_truth(self) -> dict[str, Any]: ...
