"""Reviewed, file-bound plate estimates. RFQs never supply time, mass or prices."""
from __future__ import annotations
from dataclasses import asdict
from datetime import datetime
from decimal import Decimal, InvalidOperation
import hashlib
import json
from pathlib import Path
import re
import zipfile
from itertools import product
import math
from schemas import Part, RFQ
from suppliers.print_calendar import Plate, PrintUnavailable


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def canonical_parts(raw):
    return sorted((json.loads(json.dumps(asdict(Part(**p)))) for p in raw),key=lambda p:p['part_id'])


class SavedPrintEstimates:
    def __init__(self,path: str | Path,*,allow_synthetic: bool=False):
        self.path=Path(path).resolve()
        try:
            data=self.path.read_bytes();document=json.loads(data)
            self.file_sha256=digest(data)
            self.synthetic=document.get('origin')=='synthetic_fixture'
            review=document['review']
            if self.synthetic:
                if not allow_synthetic or review['status']!='synthetic_fixture':
                    raise PrintUnavailable('Synthetic slicer estimates are permitted only in labeled fixture configuration')
            else:
                if document.get('origin')!='reviewed_slicer_estimates' or review['status']!='reviewed':
                    raise PrintUnavailable('Saved slicer estimates require explicit human review')
                if not review.get('reviewer'):raise PrintUnavailable('Saved slicer estimates need a reviewer')
                datetime.fromisoformat(review['reviewed_at'])
            self.records=document['estimates']
            if not isinstance(self.records,list):raise PrintUnavailable('Saved estimates must be a list')
            ids=[r['estimate_id'] for r in self.records]
            if any(not isinstance(i,str) or not i for i in ids) or len(ids)!=len(set(ids)):
                raise PrintUnavailable('Saved estimate IDs must be distinct strings')
        except PrintUnavailable:raise
        except (OSError,ValueError,KeyError,TypeError) as exc:
            raise PrintUnavailable('Saved slicer estimates unavailable or invalid: '+type(exc).__name__) from None

    def _artifact(self,source,path_key='path',hash_key='sha256',*,metadata=False):
        expected=source[hash_key]
        if not isinstance(expected,str) or not re.fullmatch('[0-9a-f]{64}',expected):
            raise PrintUnavailable('Source artifact needs a SHA-256')
        if self.synthetic:return b''
        path=(self.path.parent/source[path_key]).resolve()
        snippets=set()
        def scan(stream):
            hashed=hashlib.sha256()
            marker=rb'^;\s*(?:generated by PrusaSlicer\b|BambuStudio\s|filament used \[g\]|estimated printing time \(normal mode\)|filament_type\s*[=:]|model printing time:|total filament weight \[g\]\s*:)'
            for line in stream:
                hashed.update(line)
                if re.match(marker,line):
                    if len(line)>4096 or len(snippets)>32:raise PrintUnavailable('Ambiguous or oversized slicer metadata')
                    snippets.add(line.rstrip(b'\r\n'))
            return hashed.hexdigest()
        if metadata and source.get('gcode_member'):
            container_hash=source.get('container_sha256')
            if not isinstance(container_hash,str) or not re.fullmatch('[0-9a-f]{64}',container_hash):
                raise PrintUnavailable('Sliced 3MF needs a container SHA-256')
            with path.open('rb') as container:
                if hashlib.file_digest(container,'sha256').hexdigest()!=container_hash:
                    raise PrintUnavailable('Sliced 3MF container changed since preparation')
            with zipfile.ZipFile(path) as archive:
                member=source['gcode_member']
                if archive.namelist().count(member)!=1 or not member.endswith('.gcode'):
                    raise PrintUnavailable('Sliced 3MF must identify one unique G-code member')
                if archive.getinfo(member).file_size>256*1024*1024:
                    raise PrintUnavailable('Sliced G-code exceeds the supported evidence size')
                with archive.open(member) as stream:actual=scan(stream)
        else:
            with path.open('rb') as stream:
                if metadata:
                    actual=scan(stream)
                else:actual=hashlib.file_digest(stream,'sha256').hexdigest()
        if actual!=expected:raise PrintUnavailable('Slicer/geometry/profile source artifact changed since review')
        return b'\n'.join(sorted(snippets))

    def resolve(self,rfq: RFQ) -> list[tuple[Plate,...]]:
        try:
            if digest(self.path.read_bytes())!=self.file_sha256:
                raise PrintUnavailable('Saved estimate file changed; reload reviewed configuration')
            parts=canonical_parts(rfq.specs['parts'])
            if not parts or any(p['kind']!='print' for p in parts):raise PrintUnavailable('Print Part records required')
            if len({p['part_id'] for p in parts})!=len(parts) or set(rfq.part_ids)!={p['part_id'] for p in parts}:
                raise PrintUnavailable('RFQ part IDs must match the requested sliced parts')
            matches=[r for r in self.records if r['order_id']==rfq.order_id and canonical_parts(r['parts'])==parts]
            if not matches:
                # Independently sliced single-part plates can be quoted together
                # without inventing a new batched slice or scaling usage.
                groups=[[r for r in self.records if r['order_id']==rfq.order_id and canonical_parts(r['parts'])==[part]] for part in parts]
                if all(groups):
                    if math.prod(map(len,groups))>256:raise PrintUnavailable('Too many alternative reviewed plate combinations')
                    matches=[{'estimate_id':'combined:'+':'.join(r['estimate_id'] for r in choice),
                              'parts':parts,'plates':[plate for r in choice for plate in r['plates']]}
                             for choice in product(*groups)]
            if not matches:raise PrintUnavailable('Missing reviewed slicer estimate for this order, geometry requirements and quantity')
            result=[]
            for record in matches:
                counts={p['part_id']:0 for p in parts};by_id={p['part_id']:p for p in parts};plates=[]
                for raw in record['plates']:
                    if raw.get('quantity_included') is not True:raise PrintUnavailable('Plate duration must already include its declared quantities')
                    seconds=raw['machine_seconds'];grams=Decimal(str(raw['filament_g']))
                    if type(seconds) is not int or seconds<=0 or not grams.is_finite() or grams<=0:
                        raise PrintUnavailable('Positive saved machine_seconds and filament_g required')
                    quantities=raw['quantities']
                    if not quantities or any(k not in counts or type(v) is not int or v<1 for k,v in quantities.items()):
                        raise PrintUnavailable('Invalid sliced plate quantities')
                    if any(by_id[k]['material']!=raw['material'] for k in quantities):
                        raise PrintUnavailable('Sliced plate material differs from requested material')
                    sources=raw['geometry_sources']
                    if {s['part_id'] for s in sources}!=set(quantities):raise PrintUnavailable('Every sliced part needs geometry source evidence')
                    for source in sources:
                        if not source.get('uri') or not source.get('revision'):raise PrintUnavailable('Geometry URI and exact revision required')
                        self._artifact(source)
                    if not raw['printer_profile'].get('id') or not raw['print_settings'].get('id'):
                        raise PrintUnavailable('Saved printer profile and print settings need identities')
                    self._artifact(raw['printer_profile']);self._artifact(raw['print_settings'])
                    slicer=raw['slicer']
                    if slicer.get('name') not in ('PrusaSlicer','BambuStudio') or not isinstance(slicer.get('version'),str) or not slicer['version']:
                        raise PrintUnavailable('Only explicitly identified PrusaSlicer or BambuStudio evidence is supported')
                    gcode=self._artifact(raw['source'],'gcode_path','gcode_sha256',metadata=True)
                    if not self.synthetic:
                        from factoryos.quoting import slicer_usage
                        text=gcode.decode('utf-8')
                        if slicer['name']=='PrusaSlicer':
                            if set(re.findall(r'generated by PrusaSlicer\s+(\S+)',text))!={slicer['version']}:
                                raise PrintUnavailable('G-code slicer provenance does not match reviewed record')
                            try:actual_grams,actual_seconds,_=slicer_usage(text)
                            except ValueError as exc:raise PrintUnavailable('Saved slicer usage unavailable: '+str(exc)) from None
                        else:
                            if set(re.findall(r'^;\s*BambuStudio\s+(\S+)\s*$',text,re.M))!={slicer['version']}:
                                raise PrintUnavailable('BambuStudio version does not match reviewed record')
                            masses=set(re.findall(r'^;\s*total filament weight \[g\]\s*:\s*(\d+(?:\.\d+)?)\s*$',text,re.M))
                            times=set(re.findall(r'^;\s*model printing time:[^\r\n;]+;\s*total estimated time:\s*([^\r\n]+)',text,re.M))
                            if len(masses)!=1 or len(times)!=1:raise PrintUnavailable('Missing or ambiguous BambuStudio time/mass metadata')
                            duration=next(iter(times)).strip()
                            if not re.fullmatch(r'(?:\d+\s*[dhms]\s*)+',duration):raise PrintUnavailable('Unsupported BambuStudio duration')
                            chunks=re.findall(r'(\d+)\s*([dhms])',duration)
                            units=[u for _,u in chunks]
                            if len(units)!=len(set(units)) or units!=sorted(units,key='dhms'.index):raise PrintUnavailable('Ambiguous BambuStudio duration units')
                            actual_seconds=sum(int(v)*{'d':86400,'h':3600,'m':60,'s':1}[u] for v,u in chunks)
                            actual_grams=Decimal(next(iter(masses)))
                        if actual_seconds!=seconds or actual_grams!=grams:
                            raise PrintUnavailable('Saved time/mass disagrees with the whole-plate slicer metadata')
                        materials=re.findall(r'^;\s*filament_type\s*=\s*([^\r\n]+)',text,re.M)
                        if {m.strip() for m in materials}!={raw['material']}:
                            raise PrintUnavailable('G-code material metadata missing or different from the reviewed plate')
                    for key,value in quantities.items():counts[key]+=value
                    plates.append(Plate(record['estimate_id']+':'+raw['plate_id'],seconds,str(grams),raw['material'],
                        raw['printer_profile']['sha256'],raw['print_settings']['sha256'],
                        record['estimate_id']+':'+self.file_sha256,
                        'synthetic_fixture' if self.synthetic else 'reviewed_slicer_estimates'))
                if counts!={p['part_id']:p['qty'] for p in parts}:
                    raise PrintUnavailable('Sliced plate quantities must sum exactly to the requested quantities; no scaling from one part')
                if not plates or len({p.plate_id for p in plates})!=len(plates):raise PrintUnavailable('Distinct nonempty plate records required')
                result.append(tuple(plates))
            return result
        except PrintUnavailable:raise
        except (OSError,ValueError,KeyError,TypeError,InvalidOperation,zipfile.BadZipFile) as exc:
            raise PrintUnavailable('Saved slicer evidence invalid/unavailable: '+type(exc).__name__) from None
